    for rel, label in SECTIONS:
        files = py_files(rel)
        if not files:
            continue
        parts.append(f"<h2>{html.escape(label)}</h2><table><tr><th>File</th><th>What it does</th></tr>")
        for fn in files:
            key = f"{rel}/{fn}"
            desc = OVERRIDES.get(key) or first_description(os.path.join(ROOT, rel, fn))
            cell = html.escape(desc) if desc else '<span class="mut"><i>no description</i></span>'
            parts.append(f'<tr><td class="td"><code>{html.escape(key)}</code></td><td>{cell}</td></tr>')
        parts.append("</table>")
    parts.append("<h2>Other files and folders</h2><table><tr><th>Path</th><th>What it is</th></tr>")
    for path, desc in OTHER_FILES:
        parts.append(f'<tr><td class="td"><code>{html.escape(path)}</code></td><td>{html.escape(desc)}</td></tr>')
    parts.append("</table>")
    return page("CowMRP files", "".join(parts))


