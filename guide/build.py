def first_description(path):
    """First meaningful line of a module docstring: skips a bare file name and ===== underlines, strips 'name.py -- '."""
    with open(path, encoding="utf8") as f:
        try:
            doc = ast.get_docstring(ast.parse(f.read()))
        except SyntaxError:
            return None
    if not doc:
        return None
    lines, started = [], False
    for line in doc.splitlines():
        s = line.strip()
        if not s:
            if started:
                break                                    # end of the first paragraph
            continue
        if set(s) <= set("=-~"):
            continue
        s = re.sub(r"^[\w./]+\s+--?\s+", "", s)                # 'cow/x.py -- text'  ->  'text'
        if not started and s.endswith(".py") and " " not in s:   # the line is only the file name
            continue
        started = True
        lines.append(s)
    if not lines:
        return None
    text = " ".join(lines)
    text = re.split(r"(?<=[.?!])\s", text, maxsplit=1)[0].rstrip(":").strip()   # first sentence
    if len(text) > 200:
        text = text[:200].rsplit(" ", 1)[0] + " ..."
    return text


def py_files(rel):
    d = os.path.join(ROOT, rel)
    if not os.path.isdir(d):
        return []
    return sorted(f for f in os.listdir(d) if f.endswith(".py"))


def coverage():
    """Docstring coverage per package (modules, classes, functions). Returns rows and prints a report."""
    rows = []
    for pkg in (P + "/mrp", P + "/domains/cow", P + "/domains/youngstock", P + "/viz", P + "/io"):
        total = documented = 0
        missing = []
        for dirpath, dirs, files in os.walk(os.path.join(ROOT, pkg)):
            dirs[:] = [d for d in dirs if d not in ("__pycache__", "tests", "analysis")]
            for fn in files:
                if not fn.endswith(".py"):
                    continue
                p = os.path.join(dirpath, fn)
                rel = os.path.relpath(p, ROOT).replace(os.sep, "/")
                tree = ast.parse(open(p, encoding="utf8").read())
                nodes = [(rel, tree)] + [(f"{rel}:{n.name}", n) for n in ast.walk(tree)
                                         if isinstance(n, (ast.FunctionDef, ast.ClassDef)) and not n.name.startswith("_")]
                for name, node in nodes:
                    total += 1
                    if ast.get_docstring(node):
                        documented += 1
                    else:
                        missing.append(name)
        rows.append((pkg, documented, total, missing))
    print("Docstring coverage (public API pages in guide/site/api):")
    for pkg, d, t, missing in rows:
        print(f"  {pkg:20s} {d:4d} / {t:4d}  ({100 * d / max(t, 1):.0f}%)  - {t - d} without a docstring")
    if "--check" in sys.argv:
        for pkg, d, t, missing in rows:
            for m in missing:
                print(f"    missing: {m}")
    return rows


