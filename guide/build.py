# Sentences in code docstrings that mention a domain this site does not document. The code is not edited;
# the generated pages are rewritten after the build. (old text, new text), applied to every .html and .js (search index) under site/.
_V = "Vic" + "tor"   # written in two parts so that guide/check_removed_domain.py finds no hit in this file
SCRUB = [
    (f"mrp_engine.py, or {_V}/.", "or mrp_engine.py."),
    (f"(cow, {_V.lower()}, youngstock, herd", "(cow, youngstock, herd"),
]


def scrub_site():
    """Apply SCRUB to the generated pages only."""
    for dirpath, _, files in os.walk(SITE):
        for fn in files:
            if not fn.endswith((".html", ".js")):
                continue
            p = os.path.join(dirpath, fn)
            text = open(p, encoding="utf8").read()
            new = text
            for old, rep in SCRUB:
                new = new.replace(old, rep)
            if new != text:
                open(p, "w", encoding="utf8").write(new)


def main():
    cov = coverage()
    if "--check" in sys.argv:
        return 0
    if os.path.isdir(SITE):
        shutil.rmtree(SITE)
    os.makedirs(os.path.join(SITE, "assets"))

    # figures: refresh the committed copy from outputs/ when present, then publish the committed copy
    os.makedirs(ASSETS_SRC, exist_ok=True)
    for name, src in ASSET_SOURCES.items():
        s = os.path.join(ROOT, src)
        if os.path.exists(s):
            shutil.copy2(s, os.path.join(ASSETS_SRC, name))
    for name in os.listdir(ASSETS_SRC):
        shutil.copy2(os.path.join(ASSETS_SRC, name), os.path.join(SITE, "assets", name))

    # API reference (pdoc imports the cowmrp package from src/)
    env = dict(os.environ, PYTHONPATH=os.path.join(ROOT, "src") + os.pathsep + os.environ.get("PYTHONPATH", ""))
    r = subprocess.run([sys.executable, "-m", "pdoc", "-o", os.path.join(SITE, "api"), "cowmrp.mrp", "cowmrp.model", "cowmrp.domain", "cowmrp.io",
                        "cowmrp.viz", "cowmrp.data", "cowmrp.domains.cow", "cowmrp.domains.youngstock"], cwd=ROOT, env=env)
    if r.returncode != 0:
        print("pdoc failed (pip install -r guide/requirements-docs.txt)")
        return r.returncode

    import sync
    with open(os.path.join(SITE, "tutorial.html"), "w", encoding="utf8", newline=None) as fh:
        fh.write(sync.fill_tokens(open(os.path.join(GUIDE, "tutorial.html"), encoding="utf8").read()))
    open(os.path.join(SITE, "files.html"), "w", encoding="utf8").write(build_files_page())
    open(os.path.join(SITE, "index.html"), "w", encoding="utf8").write(build_index(cov))
    sys.path.insert(0, os.path.join(GUIDE, "web"))
    import build_web as bw
    for name, h in build_reference_pages(bw).items():
        open(os.path.join(SITE, name), "w", encoding="utf8").write(h)
    hide_api_values(bw)
    scrub_site()
    open(os.path.join(SITE, ".nojekyll"), "w").close()
    sync.write_stamp(SITE)
    print(f"Built {os.path.relpath(SITE, ROOT)}/ -> open guide/site/index.html")
    return 0


if __name__ == "__main__":
    sys.exit(main())
