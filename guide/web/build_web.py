def read(path):
    with open(path, encoding="utf8") as f:
        return f.read()


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf8", newline="\n") as f:
        f.write(text)


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()[:16]


def esc(s):
    return html.escape(s, quote=False)


def strip_docstring(src):
    """The example's module docstring is the description shown above the code, so the code block starts after it."""
    m = re.match(r'\s*"""(.*?)"""[ \t]*\r?\n', src, flags=re.S)
    return src[m.end():] if m else src


def code_block(text, cls=""):
    return f'<pre class="{cls}"><code>{esc(text.rstrip())}</code></pre>'


