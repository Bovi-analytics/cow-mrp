    code = lambda t: re.sub(r"`([^`]+)`", r"<code>\1</code>", html.escape(t.strip(), quote=False))
    rows_html = [f'<tr><td><a href="{repo}/blob/main/user_examples/{n}.ipynb"><code>{n}</code></a></td><td>{code(w)}</td><td>{code(i)}</td></tr>' for n, w, i in rows]
