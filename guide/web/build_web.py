def hide_long_values(t, mod, pre):
    """Replace the "show" button and raw value of the variables named in HIDE_VALUES (page of module ``mod``) by a short note."""
    names = set(HIDE_VALUES.get(mod, []))
    if not names:
        return t

    def sub(m):
        name = m.group(2)
        if name not in names:
            return m.group(0)
        note = HIDDEN_NOTE_PROV.format(pre=pre) if (mod, name) in PROVENANCE_NAMES else HIDDEN_NOTE_METHODS.format(pre=pre) if name in METHOD_INFO_NAMES else (HIDDEN_NOTE_CSS if name == "PAGE_CSS" else HIDDEN_NOTE)
        return m.group(1) + note
    return VAR_RE.sub(sub, t)


