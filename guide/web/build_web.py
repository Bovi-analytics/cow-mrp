def search_index(pages):
    docs = []
    for url, h in pages.items():
        body = re.search(r"<article>(.*?)</article>", h, flags=re.S).group(1)
        heads = re.findall(r"<h[23][^>]*>(.*?)</h[23]>", body, flags=re.S)
        text = re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", body))
        title = re.search(r"<title>(.*?) - CowMRP", h).group(1)
        docs.append({"u": url, "t": html.unescape(title), "h": " | ".join(html.unescape(re.sub(r"<[^>]+>", "", x)).strip() for x in heads), "x": html.unescape(text)[:700]})
    return "window.COWMRP_SEARCH=" + json.dumps(docs, ensure_ascii=False) + ";"


def build_api():
    env = env_with_src()
    r = subprocess.run([sys.executable, "-m", "pdoc", "-o", os.path.join(SITE, "api")] + API_MODULES, cwd=ROOT, env=env)
    if r.returncode != 0:
        sys.exit("pdoc failed (pip install -r guide/requirements-docs.txt)")
    import build as legacy                         # guide/build.py: reuse its list of docstring sentences that must not appear
    api_root = os.path.join(SITE, "api")
    for dp, _, files in os.walk(api_root):
        for fn in files:
            p = os.path.join(dp, fn)
            if not fn.endswith((".html", ".js")):
                continue
            t = read(p)
            for old, new in legacy.SCRUB:
                t = t.replace(old, new)
            if fn.endswith(".html"):
                depth = os.path.relpath(p, SITE).count(os.sep)
                pre = "../" * depth
                t = hide_long_values(t, os.path.relpath(p, api_root)[:-5].replace(os.sep, ".").replace("cowmrp.", "", 1), pre)
                t = t.replace("</head>", f'{THEME_INIT}<link rel="icon" href="{pre}assets/logo-64.png"><link rel="stylesheet" href="{pre}assets/api-bar.css"></head>', 1)
                t = re.sub(r"<body[^>]*>", lambda m: '<body class="api-page">' + header(pre, "API"), t, count=1)
                t = t.replace("</body>", f'<script src="{pre}assets/web.js"></script></body>', 1)
            write(p, nologo(t))


def api_bar_css(css):
    """Only the variables, the header and the API tail of web.css, so pdoc's own styling of its pages is not disturbed."""
    vars_ = css.split("*{box-sizing")[0]                                 # includes the @font-face block and the colour variables
    hdr = css[css.index("/* header */"):css.index("/* page layout")]
    tail = css[css.index("/* API reference"):]
    return vars_ + "a.brand,.nav a,.results a{text-decoration:none}\n.site-header,.site-header *{font-family:var(--serif)}\n.site-header code{font-family:var(--mono)}\n" + hdr + tail


