def _scalar(x):
    return not isinstance(x, (dict, list, tuple, set, frozenset)) and not hasattr(x, "to_dict") and not hasattr(x, "__dataclass_fields__")


def _as_dict(x):
    if hasattr(x, "__dataclass_fields__"):
        return {f: getattr(x, f) for f in x.__dataclass_fields__}
    return x


def _key(k):
    return " / ".join(str(p) for p in k) if isinstance(k, tuple) else str(k)


def leaves(x):
    """Every key and scalar of a value as text (what provenance.html must show); the completeness check uses it."""
    if hasattr(x, "columns") and hasattr(x, "iloc"):
        for c in x.columns:
            yield str(c)
        for v in x.to_numpy().ravel():
            yield str(v)
    elif hasattr(x, "__dataclass_fields__") or isinstance(x, dict):
        for k, v in _as_dict(x).items():
            yield from ([str(p) for p in k] if isinstance(k, tuple) else [str(k)])
            yield from leaves(v)
    elif isinstance(x, (list, tuple, set, frozenset)):
        for v in (sorted(x, key=str) if isinstance(x, (set, frozenset)) else x):
            yield from leaves(v)
    elif callable(x):
        yield getattr(x, "__name__", str(x))
    else:
        yield str(x)


def _e(v):
    return esc(str(v))


def render_value(x):
    """Readable HTML for any provenance value: nested tables for dictionaries, lists for lists, tables for lists of records and DataFrames."""
    if hasattr(x, "columns") and hasattr(x, "iloc"):
        head = "".join(f"<th>{_e(c)}</th>" for c in x.columns)
        body = "".join("<tr>" + "".join(f"<td>{_e(v)}</td>" for v in row) + "</tr>" for row in x.to_numpy())
        return f'<table class="method"><tr>{head}</tr>{body}</table>'
    if hasattr(x, "__dataclass_fields__") or isinstance(x, dict):
        rows = "".join(f"<tr><th>{_e(_key(k))}</th><td>{render_value(v)}</td></tr>" for k, v in _as_dict(x).items())
        return f'<table class="method">{rows}</table>'
    if isinstance(x, (list, tuple, set, frozenset)):
        items = sorted(x, key=str) if isinstance(x, (set, frozenset)) else list(x)
        if not items:
            return '<span class="mut">none</span>'
        if all(isinstance(i, dict) for i in items) and len({tuple(i) for i in items}) == 1:
            cols = list(items[0])
            head = "".join(f"<th>{_e(c)}</th>" for c in cols)
            body = "".join("<tr>" + "".join(f"<td>{render_value(i[c])}</td>" for c in cols) + "</tr>" for i in items)
            return f'<table class="method"><tr>{head}</tr>{body}</table>'
        if all(_scalar(i) and not isinstance(i, str) for i in items):
            return " ".join(f"<code>{_e(i)}</code>" for i in items)
        return "<ul>" + "".join(f"<li>{render_value(i)}</li>" for i in items) + "</ul>"
    if callable(x):
        return f"<code>{_e(getattr(x, '__name__', x))}</code>"
    if isinstance(x, str):
        return _e(x)
    return f"<code>{_e(x)}</code>"


