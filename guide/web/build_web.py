def prepare_logo(assets):
    """Copy the tracked processed logos (theme/logo.png, theme/logo-64.png) to assets/. Only when they are missing are they made from
    logos/Cow_MRPlogo2.png (git-ignored; the original is never modified): crop the white margin, then write assets/logo.png (hero) and
    logo-64.png (header, favicon). To change the logo, delete the two tracked files, build once with the new original in logos/, and commit
    the two files that appear in theme/."""
    tracked = [os.path.join(THEME, n) for n in ("logo.png", "logo-64.png")]
    if all(os.path.exists(t) for t in tracked):
        for t in tracked:
            shutil.copy2(t, assets)
        return True
    from PIL import Image
    src = os.path.join(ROOT, "logos", "Cow_MRPlogo2.png")
    if not os.path.exists(src):
        return False
    im = Image.open(src).convert("RGB")
    im = Image.merge("RGB", [c.point(lambda v: 255 if v >= 238 else v) for c in im.split()])     # near-white background (compression noise) -> pure white
    # a pixel is content when any channel is clearly below white
    r, g, b = im.split()
    from PIL import ImageChops
    ink = ImageChops.lighter(ImageChops.lighter(ImageChops.invert(r), ImageChops.invert(g)), ImageChops.invert(b)).point(lambda v: 255 if v > 24 else 0)
    x0, y0, x1, y1 = ink.getbbox()
    pad = int(0.04 * max(x1 - x0, y1 - y0))
    side = max(x1 - x0, y1 - y0) + 2 * pad                       # square canvas, content centred
    canvas = Image.new("RGB", (side, side), (255, 255, 255))
    canvas.paste(im.crop((x0, y0, x1, y1)), ((side - (x1 - x0)) // 2, (side - (y1 - y0)) // 2))
    canvas.resize((480, 480), Image.LANCZOS).save(os.path.join(assets, "logo.png"), optimize=True)
    canvas.resize((64, 64), Image.LANCZOS).save(os.path.join(assets, "logo-64.png"), optimize=True)
    return True


